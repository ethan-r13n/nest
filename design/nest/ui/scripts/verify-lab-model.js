const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({window:{}});
vm.runInContext(fs.readFileSync(path.join(root,'lab-model.js'),'utf8'),context);
const M=context.window.NestLabModel;
let draft=M.blank();
draft=M.parse('Compare XLM/USDC on Soroswap and Aquarius. Notify me when the deviation is greater than 1.25%. Estimate how much size fits with max impact 0.5%.',draft,'backtest');
assert.equal(draft.venueA,'Soroswap');assert.equal(draft.venueB,'Aquarius');assert.equal(draft.pair,'XLM/USDC');
assert.equal(draft.threshold,'1.25');assert.equal(draft.sizing,'capacity');assert.equal(draft.maxImpact,'0.5');
assert.equal(M.missing(draft,'backtest')[0],'pools');
draft=M.parse('Pool A: soroswap-pool-a; Pool B: aquarius-pool-b',draft,'backtest');
assert.equal(draft.poolA,'soroswap-pool-a');assert.equal(draft.poolB,'aquarius-pool-b');
assert.equal(M.missing(draft,'backtest')[0],'period');
draft=M.parse('Last 90 days, with 60 bps in round-trip fees',draft,'backtest');
assert.equal(draft.days,'90');assert.equal(draft.costBps,'60');assert.equal(M.missing(draft,'backtest').length,0);
assert.equal(M.missing(draft,'automation')[0],'cadence');
draft=M.parse('Every 5 minutes, until paused',draft,'automation');
assert.equal(draft.cadence,'300');assert.equal(draft.lifetime,'until-paused');assert.equal(M.missing(draft,'automation').length,0);
const fingerprint=M.fingerprint(draft,'automation');
assert.equal(M.fingerprint({...draft,chart:'prices'},'automation'),fingerprint);
draft=M.parse('Use 1,000 USDC',draft,'automation');assert.equal(draft.amount,'1000');assert.equal(draft.sizing,'fixed');
assert.notEqual(M.fingerprint(draft,'automation'),fingerprint);
assert.equal(M.parse('0 bps',draft,'backtest').costBps,'0');
let short={...draft,threshold:'',maxImpact:''};
short=M.parse('2%',short,'backtest');assert.equal(short.threshold,'2');assert.equal(short.maxImpact,'');
short=M.parse('0.75%',short,'backtest');assert.equal(short.maxImpact,'0.75');assert.equal(short.threshold,'2');
assert.ok(M.missing({...draft,poolB:draft.poolA},'backtest').includes('pools'));
assert.ok(M.missing({...draft,threshold:'-1'},'backtest').includes('threshold'));
assert.ok(M.missing({...draft,amount:'0'},'backtest').includes('sizing'));
assert.ok(M.missing({...draft,cadence:'1'},'automation').includes('cadence'));
assert.ok(M.missing({...draft,pair:'XLM/XLM'},'backtest').includes('pair'));
assert.ok(M.missing({...draft,costBps:''},'backtest').includes('costs'));
assert.equal(M.validDraft({pair:5,thesis:'valid'}).pair,'');
assert.equal(M.validDraft({unexpected:'ignored'}).unexpected,undefined);
let urlDraft=M.parse('Compare XLM/USDC on Soroswap and Aquarius. https://example.com/pool/a https://example.com/pool/b',M.blank(),'backtest');
assert.equal(urlDraft.poolA,'https://example.com/pool/a');assert.equal(urlDraft.poolB,'https://example.com/pool/b');
let incremental={...urlDraft,poolA:'',poolB:''};
incremental=M.parse('https://example.com/pool/a',incremental,'backtest');
assert.equal(incremental.poolA,'https://example.com/pool/a');assert.match(M.next(incremental,'backtest'),/Aquarius pool/);
incremental=M.parse('https://example.com/pool/b',incremental,'backtest');assert.equal(incremental.poolB,'https://example.com/pool/b');
// Different signal ideas retain their own source and condition instead of asking for arbitrage pools.
let signal=M.parse('If the BTC/USD daily close crosses above its 20-day EMA, propose to buy XLM for my review.',M.blank(),'automation');
assert.equal(signal.kind,'btc-ema');assert.equal(signal.response,'review');assert.equal(signal.targetAsset,'XLM');
assert.equal(M.missing(signal,'automation')[0],'signalSource');assert.ok(!M.missing(signal,'automation').includes('pools'));
signal=M.parse('Source: example BTC/USD daily candle feed',signal,'automation');
assert.equal(M.missing(signal,'automation')[0],'signalSizing');
signal=M.parse('1,000 USDC',signal,'automation');assert.equal(signal.amount,'1000');
signal=M.parse('Every 5 minutes until paused',signal,'automation');assert.equal(M.missing(signal,'automation').length,0);
assert.match(M.summary(signal,'automation').sizing,/review required/);assert.ok(!M.next(signal,'automation').includes('chart'));
let volume=M.parse('Notify me if XLM/USD breaks its 30-day high with volume above 2 times its 20-day average.',M.blank(),'backtest');
assert.equal(volume.kind,'volume-breakout');assert.equal(volume.response,'alert');
volume=M.parse('Source: example XLM/USD candles; last 90 days',volume,'backtest');assert.equal(M.missing(volume,'backtest').length,0);
let yieldGap=M.parse('Alert only if the USDC supply rate exceeds my current venue by 2 percentage points for 24 hours.',M.blank(),'automation');
assert.equal(yieldGap.kind,'yield-gap');assert.equal(yieldGap.response,'alert');assert.equal(M.missing(yieldGap,'automation')[0],'signalSource');
assert.ok(!M.missing(yieldGap,'automation').includes('pools'));
// Render the empty views and restore saved records without depending on a browser.
const escape=value=>String(value??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const saved=new Map();
context.localStorage={getItem:key=>saved.get(key)||null,setItem:(key,value)=>saved.set(key,value)};
context.window.NestUI={escape};context.window.NestScreens={};context.window.NestBinders={};
vm.runInContext(fs.readFileSync(path.join(root,'screens/lab.js'),'utf8'),context);
for(const route of ['lab-backtests','lab-automation','lab-history']){
 const html=context.window.NestScreens[route]();assert.match(html,/Strategy chat|Strategy history/);assert.ok(!html.includes('Strategy canvas')&&!html.includes('lab-chart-content'));
 assert.ok(!/Knowledge graph|Learning runs|Connect X|Run sample backtest/.test(html));
 assert.equal((html.match(/class="tab /g)||[]).length,3);
}
saved.set('nest.lab.strategy.v2',JSON.stringify({draft,entries:[{id:'test-record',mode:'backtest',draft:{...draft,thesis:'<img src=x onerror=alert(1)>'},messages:[],createdAt:'2026-10-25T18:00:00Z'}]}));
vm.runInContext(fs.readFileSync(path.join(root,'screens/lab.js'),'utf8'),context);
const history=context.window.NestScreens['lab-history']();
assert.ok(!history.includes('<img src=x'));assert.match(history,/&lt;img/);assert.match(history,/Awaiting historical data/);
assert.ok(!history.includes('Profitable')&&!history.includes('Active monitor'));
console.log(JSON.stringify({result:'passed',checked:['natural-language thesis extraction','guided follow-ups','fixed and capacity sizing','mode-specific time requirements','missing/invalid input gating','revision changes','three Lab views','safe persisted history','truthful source states','EMA, breakout and yield ideas retain distinct conditions','canvas removed from all Lab views']},null,2));
